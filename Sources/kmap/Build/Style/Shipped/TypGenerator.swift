import Foundation

/// Turns a palette table into a TYP source the mkgmap compiler takes.
///
/// The table is the whole input: every polygon becomes a `[_polygon]`, every line a
/// `[_line]`, and the draw order is read off the levels. Night colours are not in the
/// table — they are derived, by dimming the day colour and snapping each channel to the
/// four steps a MIP watch can actually show (0, 85, 170, 255). A night palette drawn in
/// finer steps looks fine on paper and collapses to mud on the wrist.
enum TypGenerator {

    /// `points` is a block of ready `[_point]` sections appended as it is — icons are
    /// bitmaps made once from their SVGs, not something to regenerate at build time.
    ///
    /// `graphics` is a block of ready `[_polygon]`/`[_line]` sections, a style's own
    /// pattern drawings taken whole: a section whose code the palette carries REPLACES
    /// the flat colour that would be generated, a line section for a code the palette
    /// does not carry is appended, and a polygon for an unknown code is dropped — a
    /// polygon needs a draw order, and the palette is where draw orders live.
    static func text(from palette: StylePalette, fid: Int, productCode: Int = 1,
                     points: String = "", graphics: String = "") -> String {
        let overrides = parseGraphics(graphics)
        var out: [String] = []
        out.append("; -*- coding: UTF-8 -*-")
        out.append("; \(palette.name) — generated by kmap from its palette table.")
        out.append("; Edit the table, not this file: the next build writes it again.")
        out.append("")
        out.append("[_id]")
        out.append("FID=\(fid)")
        out.append("ProductCode=\(productCode)")
        out.append("CodePage=1252")
        out.append("[end]")
        out.append("")

        out.append("[_drawOrder]")
        for poly in palette.polygons.sorted(by: { ($0.level, $0.code) < ($1.level, $1.code) }) {
            out.append(String(format: "Type=0x%03x,%d", poly.code, poly.level))
        }
        out.append("[end]")
        out.append("")

        for poly in palette.polygons {
            if let section = overrides.polygons[poly.code] {
                out.append(named(section, poly.name))
                out.append("")
                continue
            }
            out.append("[_polygon]")
            out.append(String(format: "Type=0x%02x", poly.code))
            out.append("; \(poly.name)")
            out.append("Xpm=\"0 0 2 0\"")
            out.append("\"1 c \(poly.day)\"")
            out.append("\"2 c \(night(of: poly.night))\"")
            out.append("String=0x00,\(poly.name)")
            out.append("FontStyle=NoLabel")
            out.append("[end]")
            out.append("")
        }

        for line in palette.lines {
            if let section = overrides.lines[line.code] {
                out.append(named(section, line.name))
                out.append("")
                continue
            }
            out.append("[_line]")
            out.append(String(format: "Type=0x%02x", line.code))
            out.append("; \(line.name)")
            if let casing = line.casing {
                // The table's width is the whole stroke, casing included: one pixel of
                // border either side, ink in the middle.
                let ink = max(1, line.width - 2)
                out.append("Xpm=\"0 0 4 0\"")
                out.append("\"1 c \(line.day)\"")
                out.append("\"2 c \(casing)\"")
                out.append("\"3 c \(night(of: line.day))\"")
                out.append("\"4 c \(night(of: casing))\"")
                out.append("LineWidth=\(ink)")
                out.append("BorderWidth=1")
            } else {
                out.append("Xpm=\"0 0 2 0\"")
                out.append("\"1 c \(line.day)\"")
                out.append("\"2 c \(night(of: line.day))\"")
                out.append("LineWidth=\(line.width)")
            }
            out.append("String=0x00,\(line.name)")
            out.append("[end]")
            out.append("")
        }

        let lineCodes = Set(palette.lines.map(\.code))
        for (code, section) in overrides.lines.sorted(by: { $0.key < $1.key })
        where !lineCodes.contains(code) {
            out.append(section)
            out.append("")
        }

        if !points.isEmpty {
            out.append(points)
        }
        return out.joined(separator: "\n")
    }

    /// A borrowed section carries the label its own style wrote, in its own language.
    /// The table's name is added beside it where the section names nothing kmap's own
    /// build would read, so a device does not offer a German word for a Russian map.
    private static func named(_ section: String, _ name: String) -> String {
        guard !section.contains("String=0x00,") else { return section }
        var lines = section.components(separatedBy: "\n")
        // First, so it is the label a device reads before their own language entries.
        guard let type = lines.firstIndex(where: {
            $0.trimmingCharacters(in: .whitespaces).lowercased().hasPrefix("type=")
        }) else { return section }
        lines.insert("String=0x00,\(name)", at: type + 1)
        return lines.joined(separator: "\n")
    }

    /// Splits a graphics block into whole sections, keyed by kind and type code.
    ///
    /// Through `TypSource.parse`, the one reader of TYP text: it already knows a
    /// section's kind and code, tolerates CRLF, casing and a comment after the type,
    /// and a second hand-written splitter here accepted strictly less than it.
    static func parseGraphics(_ text: String)
    -> (polygons: [Int: String], lines: [Int: String]) {
        var polygons: [Int: String] = [:]
        var lines: [Int: String] = [:]
        guard !text.isEmpty else { return (polygons, lines) }
        let source = TypSource.parse(text)
        for section in source.sections {
            let body = source.lines[section.lines].joined(separator: "\n")
            switch section.kind {
            case .polygon: polygons[section.code] = body
            case .line: lines[section.code] = body
            default: break
            }
        }
        return (polygons, lines)
    }

    /// The night version of a day colour: dimmed to two thirds, then each channel
    /// snapped to the nearest of 0, 85, 170, 255 — the only greys a MIP display has.
    static func night(of day: String) -> String {
        guard day.count == 7, day.hasPrefix("#"),
              let value = Int(day.dropFirst(), radix: 16) else { return day }
        func snap(_ channel: Int) -> Int {
            let dimmed = channel * 2 / 3
            return ((dimmed + 42) / 85) * 85
        }
        let r = snap((value >> 16) & 0xff), g = snap((value >> 8) & 0xff), b = snap(value & 0xff)
        return String(format: "#%02X%02X%02X", r, g, b)
    }
}
