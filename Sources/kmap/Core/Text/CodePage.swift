/// The single-byte Windows code pages a Garmin map declares in its header and stores its
/// labels in. The tables are carried here rather than taken from Foundation, which outside
/// Darwin supports only UTF-8, UTF-16, ASCII and Latin-1. Generated from the unicode.org
/// mappings.
enum CodePage {

    /// UTF-8, which a TYP may declare instead of a single-byte page.
    static let utf8 = 65001

    /// The single-byte pages builds use, by the numbers the format writes them as.
    static let westernEuropean = 1252
    static let cyrillic = 1251
    static let centralEuropean = 1250

    /// Longitude in degrees east of which map names are likely Cyrillic. Drives a warning
    /// only; it sets nothing.
    static let cyrillicMeridian = 19.0

    /// The pages with a table here. Anything else falls back to Latin-1, as mkgmap does.
    static var supported: [Int] { Array(highHalves.keys).sorted() }

    // MARK: Decoding

    /// Decodes `bytes` as text in `codePage`.
    ///
    /// - Returns: The text, or nil where a byte has no character in that page.
    static func decode<Bytes: Collection>(_ bytes: Bytes, codePage: Int) -> String?
        where Bytes.Element == UInt8 {
        if codePage == utf8 { return String(bytes: bytes, encoding: .utf8) }
        guard let table = highHalves[codePage] else { return latin1(bytes) }
        var scalars = String.UnicodeScalarView()
        scalars.reserveCapacity(bytes.count)
        for byte in bytes {
            if byte < 0x80 {
                scalars.append(UnicodeScalar(byte))
            } else {
                let mapped = table[Int(byte) - 0x80]
                guard mapped != undefined, let scalar = UnicodeScalar(mapped) else { return nil }
                scalars.append(scalar)
            }
        }
        return String(scalars)
    }

    /// Decodes every byte as the scalar of the same value. Never fails.
    static func latin1<Bytes: Collection>(_ bytes: Bytes) -> String where Bytes.Element == UInt8 {
        String(String.UnicodeScalarView(bytes.map { UnicodeScalar($0) }))
    }

    /// Decodes in `codePage`, falling back to Latin-1 where the bytes do not fit it.
    static func decodeLenient<Bytes: Collection>(_ bytes: Bytes, codePage: Int) -> String
        where Bytes.Element == UInt8 {
        decode(bytes, codePage: codePage) ?? latin1(bytes)
    }

    // MARK: Encoding

    /// Encodes `text` as bytes in `codePage`.
    ///
    /// - Parameter lossy: Substitutes `?` for a character the page cannot hold.
    /// - Returns: The bytes, or nil when not `lossy` and a character does not fit.
    static func encode(_ text: String, codePage: Int, lossy: Bool = false) -> [UInt8]? {
        if codePage == utf8 { return Array(text.utf8) }
        guard let table = reverse(codePage) else {
            // Latin-1 is the identity on the first 256 scalars.
            var out = [UInt8]()
            out.reserveCapacity(text.unicodeScalars.count)
            for scalar in text.unicodeScalars {
                if scalar.value < 0x100 { out.append(UInt8(scalar.value)) }
                else if lossy { out.append(question) }
                else { return nil }
            }
            return out
        }
        // These pages hold precomposed forms only, so compose first, as Foundation does.
        var out = [UInt8]()
        let composed = text.precomposedStringWithCanonicalMapping
        out.reserveCapacity(composed.unicodeScalars.count)
        for scalar in composed.unicodeScalars {
            if scalar.value < 0x80 {
                out.append(UInt8(scalar.value))
            } else if let byte = table[scalar.value] {
                out.append(byte)
            } else if lossy {
                out.append(question)
            } else {
                return nil
            }
        }
        return out
    }

    /// Whether every character of `text` has a byte in `codePage`.
    static func canHold(_ text: String, codePage: Int) -> Bool {
        encode(text, codePage: codePage, lossy: false) != nil
    }

    // MARK: The tables

    /// No character at this byte. 0xFFFF is a permanent Unicode noncharacter.
    private static let undefined: UInt16 = 0xFFFF

