import XCTest

@testable import kmap

final class StageCompileTests: XCTestCase {
    private func tile(_ id: String, input: String = "in.osm") -> BuildPipeline.Tile {
        BuildPipeline.Tile(
            mapID: id,
            argsBlock: "mapname: \(id)\ndescription: \(id)\ninput-file: \(input)",
            bbox: .empty,
            inputSize: 0
        )
    }

    // MARK: writeTileArgs

    func testTheTilesArgumentsAreWrittenIntoAnEmptiedFolder() throws {
        let build = PipelineFixture.pipeline(workRoot: try scratchFolder())
        let tiles = BuildPipeline.TileSet(directory: try scratchFolder(), tiles: [tile("1"), tile("2")], nodeCap: 1)
        let stale = build.workDirectory.appendingPathComponent("build/tiles/63000009.img")
        Paths.ensure(stale.deletingLastPathComponent())
        try FileTools.write(Data("old".utf8), to: stale)

        let (tileDir, argsFile) = try build.writeTileArgs(tiles)

        XCTAssertEqual(argsFile.deletingLastPathComponent().standardizedFileURL, tileDir.standardizedFileURL)
        XCTAssertFalse(FileTools.exists(stale))
        XCTAssertEqual(
            try String(contentsOf: argsFile, encoding: .utf8),
            "# generated by kmap\n" + tiles.tiles.map(\.argsBlock).joined(separator: "\n\n") + "\n"
        )
    }

    // MARK: prepareTYP

    func testAStyleWithoutATYPHasNoneToPrepare() throws {
        let build = PipelineFixture.pipeline(workRoot: try scratchFolder())
        XCTAssertNil(build.prepareTYP())
        XCTAssertTrue(build.repairMoves.isEmpty)
    }

    /// The types it had to move are kept for the rules.
    func testATYPIsCopiedForTheBuildAndTheOriginalLeftAlone() throws {
        let original = try scratchFolder().appendingPathComponent("borrowed.txt")
        try FileTools.write(TypFixture.source, to: original)
        let build = PipelineFixture.pipeline(workRoot: try scratchFolder()) {
            $0.style = MapStyle(
                id: "typ:borrowed",
                name: "Borrowed",
                summary: "",
                origin: .builtin,
                styleDirectory: nil,
                typURL: original,
                familyID: 6300,
                productID: 1
            )
        }

        let typ = try XCTUnwrap(build.prepareTYP())

        XCTAssertEqual(try String(contentsOf: original, encoding: .utf8), TypFixture.source)
        XCTAssertNotEqual(typ.url.standardizedFileURL, original.standardizedFileURL)
        let scratch = build.workDirectory.appendingPathComponent("typ", isDirectory: true).standardizedFileURL.path
        XCTAssertTrue(typ.url.standardizedFileURL.path.hasPrefix(scratch), typ.url.path)
        XCTAssertTrue(FileTools.exists(typ.url))
        XCTAssertEqual(build.repairMoves, typ.moved)
        for added in typ.added {
            XCTAssertTrue(build.log.snapshot().contains { $0.text == "added to the TYP for this build: \(added)" })
        }
    }

    // MARK: planWarmStart and runCompile

    func testTheWarmStartSweepsStaleCachesAndSaysWhenItRecords() async throws {
        let toolchain = try RealMkgmap.install()
        let java = try XCTUnwrap(toolchain.findJava())
        let mkgmap = try XCTUnwrap(toolchain.findMkgmap()?.url)
        Paths.ensure(JavaWarmStart.directory)
        let stale = JavaWarmStart.directory.appendingPathComponent("warm-stale-test.aot")
        let fresh = JavaWarmStart.directory.appendingPathComponent("warm-fresh-test.aot")
        try FileTools.write(Data("old".utf8), to: stale)
        try FileTools.write(Data("new".utf8), to: fresh)
        addTeardownBlock {
            FileTools.removeIfPresent(stale)
            FileTools.removeIfPresent(fresh)
        }
        try FileDates.setModified(stale, to: Date().addingTimeInterval(-3 * JavaWarmStart.staleAfter))
        let build = PipelineFixture.pipeline(workRoot: try scratchFolder())

        let marks = Set(FileTools.contents(of: JavaWarmStart.directory).filter { $0.pathExtension == "refused" })
        let warm = try await build.planWarmStart(java: java, mkgmap: mkgmap)
        defer {
            JavaWarmStart.discard(warm)
            // A refusal this test caused would stop later tests recording.
            for mark in FileTools.contents(of: JavaWarmStart.directory)
            where mark.pathExtension == "refused" && !marks.contains(mark) {
                FileTools.removeIfPresent(mark)
            }
        }

        XCTAssertFalse(FileTools.exists(stale))
        XCTAssertTrue(FileTools.exists(fresh))
        let said = build.log.snapshot().contains { $0.text.hasPrefix("recording a warm start for mkgmap") }
        XCTAssertEqual(said, warm.recording != nil)
    }

    func testMkgmapCompilesATile() async throws {
        let toolchain = try RealMkgmap.install()
        let java = try XCTUnwrap(toolchain.findJava())
        let mkgmap = try XCTUnwrap(toolchain.findMkgmap()?.url)
        let input = try scratchFolder().appendingPathComponent("in.osm")
        try FileTools.write(
            """
            <?xml version='1.0' encoding='UTF-8'?>
            <osm version='0.6'>
            <node id='1' version='1' lat='44.95' lon='34.10'/>
            <node id='2' version='1' lat='44.96' lon='34.11'/>
            <way id='1' version='1'><nd ref='1'/><nd ref='2'/><tag k='highway' v='track'/></way>
            </osm>
            """,
            to: input
        )
        let build = PipelineFixture.pipeline(workRoot: try scratchFolder())
        let tiles = BuildPipeline.TileSet(
            directory: input.deletingLastPathComponent(),
            tiles: [tile("63000001", input: input.path)],
            nodeCap: 1_000_000
        )
        let (tileDir, argsFile) = try build.writeTileArgs(tiles)
        let warm = JavaWarmStart.Plan(cache: nil)
        let arguments =
            java.command(["-Xmx1g", "-jar", mkgmap.path])
            + ["--output-dir=\(tileDir.path)", "-c", argsFile.path]

        try await build.runCompile(
            tiles,
            java: java,
            arguments: arguments,
            tileDir: tileDir,
            warm: warm,
            mkgmap: mkgmap
        )

        XCTAssertTrue(FileTools.exists(tileDir.appendingPathComponent("63000001.img")))
    }
}
